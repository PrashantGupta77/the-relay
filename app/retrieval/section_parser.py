def normalize_line(value: str) -> str:
    return " ".join(value.strip().split())


def detect_heading(
    paper_id: str,
    lines: list[str],
    index: int,
) -> tuple[str, str, int] | None:
    """
    Accept only exact catalogued headings.

    Supported extraction layouts:
      1. '3.1 Overview'
      2. '3.1' followed by 'Overview'

    Returns:
      (section_number, section_title, consumed_line_count)
    """
    catalog = HEADING_CATALOG[paper_id]
    current = normalize_line(lines[index])

    # Number and title on the same line.
    match = re.fullmatch(r"(\d+(?:\.\d+)*)\s+(.+)", current)

    if match:
        number = match.group(1)
        title = normalize_line(match.group(2))
        expected = catalog.get(number)

        if expected and title.casefold() == expected.casefold():
            return number, expected, 1

    # Number and title on two consecutive lines.
    if re.fullmatch(r"\d+(?:\.\d+)*", current) and index + 1 < len(lines):
        number = current
        title = normalize_line(lines[index + 1])
        expected = catalog.get(number)

        if expected and title.casefold() == expected.casefold():
            return number, expected, 2

    return None


def update_section_path(
    active_sections: dict[int, dict[str, str]],
    section_number: str,
    section_title: str,
) -> list[dict[str, str]]:
    level = section_number.count(".") + 1

    # Remove the previous section at this level and all deeper levels.
    for existing_level in list(active_sections):
        if existing_level >= level:
            del active_sections[existing_level]

    active_sections[level] = {
        "section_number": section_number,
        "section_title": section_title,
    }

    return [
        dict(active_sections[key])
        for key in sorted(active_sections)
    ]


def format_section_path(path: list[dict[str, str]]) -> str | None:
    if not path:
        return None

    return " > ".join(
        f"{item['section_number']} {item['section_title']}"
        for item in path
    )


def parse_paper(input_path: Path, output_path: Path) -> dict[str, Any]:
    paper_id = input_path.stem

    if paper_id not in HEADING_CATALOG:
        raise ValueError(f"No heading catalog found for {paper_id}")

    # Retained across pages so a section continues onto the next page.
    active_sections: dict[int, dict[str, str]] = {}

    page_count = 0
    segment_count = 0
    detected_headings: list[dict[str, Any]] = []

    output_path.parent.mkdir(parents=True, exist_ok=True)

    with input_path.open("r", encoding="utf-8") as source, \
            output_path.open("w", encoding="utf-8") as destination:

        for raw_record in source:
            if not raw_record.strip():
                continue

            page = json.loads(raw_record)
            page_count += 1

            lines = page.get("retrieval_text", "").splitlines()
            segments: list[dict[str, Any]] = []

            current_lines: list[str] = []
            current_line_start = 0

            current_path = [
                dict(item)
                for _, item in sorted(active_sections.items())
            ]

            def flush_segment(end_line: int) -> None:
                nonlocal segment_count

                segment_text = "\n".join(current_lines).strip()

                if not segment_text:
                    return

                segments.append({
                    "text": segment_text,
                    "line_start": current_line_start,
                    "line_end": max(current_line_start, end_line - 1),
                    "section_number": (
                        current_path[-1]["section_number"]
                        if current_path else None
                    ),
                "section_title": (
                    current_path[-1]["section_title"]
                    if current_path else None
                ),
                "section_heading": (
                    f"{current_path[-1]['section_number']} "
                    f"{current_path[-1]['section_title']}"
                    if current_path else None
                ),
                "section_path": format_section_path(current_path),
                    "section_source": (
                        "manual_verified" if current_path else None
                    ),
                })

                segment_count += 1

            index = 0

            while index < len(lines):
                heading = detect_heading(paper_id, lines, index)

                if heading:
                    # Flush preceding text under the previous section.
                    flush_segment(index)

                    number, title, consumed = heading

                    current_path = update_section_path(
                        active_sections,
                        number,
                        title,
                    )

                    detected_headings.append({
                        "paper_id": paper_id,
                        "page_number": page.get("page_number"),
                        "section_number": number,
                        "section_title": title,
                        "section_path": format_section_path(current_path),
                        "line_index": index,
                    })

                    # Include the heading lines in the new section segment.
                    current_lines = lines[index:index + consumed]
                    current_line_start = index
                    index += consumed
                    continue

                if not current_lines:
                    current_line_start = index

                current_lines.append(lines[index])
                index += 1

            # Flush the last segment on this page.
            flush_segment(len(lines))

            # Keep original extracted fields unchanged.
            page["section_segments"] = segments
            page["section_parser_version"] = "1.0"
            page["section_parser_source"] = "manual_verified_heading_catalog"

            destination.write(
                json.dumps(page, ensure_ascii=False) + "\n"
            )

    return {
        "paper_id": paper_id,
        "pages": page_count,
        "segments": segment_count,
        "headings_detected": len(detected_headings),
        "headings": detected_headings,
    }


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    input_files = sorted(INPUT_DIR.glob("*.jsonl"))

    if not input_files:
        raise FileNotFoundError(
            f"No cleaned JSONL files found in {INPUT_DIR}"
        )

    summaries = []

    for input_path in input_files:
        output_path = OUTPUT_DIR / input_path.name

        summary = parse_paper(input_path, output_path)
        summaries.append(summary)

        print("\n" + "=" * 72)
        print(f"PAPER: {summary['paper_id']}")
        print(f"Pages: {summary['pages']}")
        print(f"Segments: {summary['segments']}")
        print(f"Detected headings: {summary['headings_detected']}")

        for heading in summary["headings"]:
            print(
                f"  Page {heading['page_number']}: "
                f"{heading['section_number']} "
                f"{heading['section_title']}"
            )

    summary_path = OUTPUT_DIR / "section_parser_summary.json"

    summary_path.write_text(
        json.dumps(summaries, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print("\n" + "=" * 72)
    print("SECTION PARSING COMPLETED")
    print(f"Summary saved to: {summary_path}")


if __name__ == "__main__":
    main()
